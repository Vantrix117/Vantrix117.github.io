/* The House Hub has moved (2026-10-11). This page stands at the old address, vantrix117.github.io/house-hub/…, and sends
   each device to the same page at the new address without pairing again:
   1. If this device is paired here (its token is in this address's localStorage), it asks the house for a one-time code
      (good for 2 minutes, once), carrying along any changes still waiting to be sent.
   2. It opens the new address with only that code in the URL fragment (never sent to any server, never a long-lived token).
   3. The new page trades the code for this device's own fresh sign-in; the old tokens stop working there and then.
   A device with nothing paired here just goes to the new address. Generated by scripts/make-move-site.mjs; no personal data. */
(function () {
  'use strict';
  var NEW = 'https://vantrix-house-hub.pages.dev', API_DEFAULT = 'https://house-hub-api.catalystfarm1.workers.dev', BASE = '/house-hub';
  function get(k) { try { var v = localStorage.getItem(k); return v == null ? null : JSON.parse(v); } catch (e) { return null; } }
  if (location.pathname.indexOf(BASE + '/') !== 0 && location.pathname !== BASE) {   // the user site's 404 for some other address
    var t = document.querySelector('h1'), m0 = document.getElementById('msg'), g0 = document.getElementById('go');
    if (t) t.textContent = 'Nothing here'; if (m0) m0.textContent = 'This address has no page.'; if (g0) g0.remove();
    return;
  }
  var path = location.pathname.slice(BASE.length);
  if (!path || path === '/index.html' || path === '/README.html') path = '/';   // the guide is no longer published
  var target = NEW.replace(/\/$/, '') + path + location.search;
  var oldHash = location.hash ? location.hash.slice(1) : '';
  var go = document.getElementById('go'); if (go) go.href = target + (oldHash ? '#' + oldHash : '');
  function leave(code) {
    var url = target + (code ? '#hh=' + encodeURIComponent(code) + (oldHash ? '&h=' + encodeURIComponent(oldHash) : '') : (oldHash ? '#' + oldHash : ''));
    try { (window.top || window).location.replace(url); } catch (e) { location.replace(url); }
  }
  var dev = get('hub.device'), sess = get('hub.session'), api = get('hub.api') || API_DEFAULT;
  if (!dev || !dev.token || !window.fetch) { leave(null); return; }
  // what is still waiting to be sent from here comes along (the new page writes it only where nothing is stored yet)
  var carry = {}, size = 0;
  try {
    for (var i = 0; i < localStorage.length; i++) {
      var k = localStorage.key(i);
      if (!/^hub\.(queue|aqueue|chatq|prefs|theme|lastProfile|fp|timers\.device)(\.|$)/.test(k)) continue;
      var v = localStorage.getItem(k); if (v == null || size + v.length > 200000) continue;
      carry[k] = v; size += v.length;
    }
  } catch (e) {}
  function ask(withSession) {
    var h = { 'Content-Type': 'application/json', 'X-Device-Token': dev.token };
    if (withSession && sess && sess.token) h['X-Profile-Token'] = sess.token;
    return fetch(api.replace(/\/$/, '') + '/api/handoff', { method: 'POST', headers: h, body: JSON.stringify({ carry: carry }), cache: 'no-store' })
      .then(function (r) { return r.json().catch(function () { return {}; }).then(function (j) { return { status: r.status, body: j }; }); });
  }
  function stuck() {   // offline, or the house did not answer: stay here (the new address could not open this device either)
    var m = document.getElementById('msg'); if (m) m.textContent = 'This device is offline or the house is not answering. It moves you as soon as it can.';
    window.addEventListener('online', function () { location.reload(); });
    setTimeout(function () { location.reload(); }, 60000);
  }
  var done = false, timer = setTimeout(function () { if (!done) { done = true; stuck(); } }, 20000);
  ask(true).then(function (a) {
    // a sign-in that ran out still moves the device (the picker shows there)
    return a.status === 401 && a.body && a.body.error === 'profile_session_invalid' ? ask(false) : a;
  }).then(function (a) {
    if (done) return; done = true; clearTimeout(timer);
    if (a.status === 200 && a.body && a.body.code) { leave(a.body.code); return; }
    if (a.status === 429 || a.status >= 500 || a.status === 0) { stuck(); return; }   // try again in a minute, keep the pairing
    // this device already moved (or was unpaired): nothing of the hub stays at the old address
    if (a.status === 401 && a.body && a.body.error === 'device_not_paired') {
      try { for (var i = localStorage.length - 1; i >= 0; i--) { var k = localStorage.key(i); if (k && k.indexOf('hub.') === 0) localStorage.removeItem(k); } } catch (e) {}
    }
    leave(null);
  }, function () { if (done) return; done = true; clearTimeout(timer); stuck(); });
})();
