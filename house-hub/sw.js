/* The House Hub has moved (2026-10-11). This service worker replaces the hub's old one at vantrix117.github.io/house-hub/.
   A Home Screen app or a browser that still has the old hub saved picks this file up on its next update check; it then
   deletes everything the old hub kept here (its saved pages and its saved photos), turns off this address's notifications,
   reloads every open hub window (which now loads the "moved" page, which hands the device to the new address) and removes
   itself. Generated by scripts/make-move-site.mjs; no personal data. */
self.addEventListener('install', e => { e.waitUntil(self.skipWaiting()); });
self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    try { for (const k of await caches.keys()) await caches.delete(k); } catch (err) {}
    try { const s = await self.registration.pushManager.getSubscription(); if (s) await s.unsubscribe(); } catch (err) {}
    try { await self.clients.claim(); } catch (err) {}
    try { for (const c of await self.clients.matchAll({ type: 'window', includeUncontrolled: true })) { try { await c.navigate(c.url); } catch (err) {} } } catch (err) {}
    try { await self.registration.unregister(); } catch (err) {}
  })());
});
// no fetch handler: every request goes to the network, so the "moved" pages always load fresh
// a push that was already on its way: say where the hub is now (a push must show something)
self.addEventListener('push', e => {
  e.waitUntil(self.registration.showNotification('House Hub has a new address', { body: 'Open the hub and turn notifications on again there.', tag: 'hub-moved' }));
});
self.addEventListener('notificationclick', e => { e.notification.close(); e.waitUntil(self.clients.openWindow('./')); });
